/// Builds the premium management report as a complete HTML/CSS document.
///
/// This builder is intended for Flutter Web. It keeps the eight-page report
/// structure supplied by the product design and uses only browser-printable
/// HTML, CSS and inline SVG. The browser can open its normal print preview and
/// save the report as PDF without using a Flutter PDF renderer.
///
/// Base pages:
/// 1. Monthly Company Report
/// 2. Portfolio Delivery Health
/// 3. Task Execution & Throughput
/// 4. Timeline, Dependencies & Milestones
/// 5. Team Capacity & Workload
/// 6. Appraisal & Performance Intelligence
/// 7. Risk, Quality & Notification Operations
/// 8. Management Actions, Audit & Export
///
/// Larger datasets add continuation pages after the fixed eight-page report.
class DynamicReportHtmlBuilder {
  const DynamicReportHtmlBuilder();

  String build({
    required ReportModel report,
    required List<Project> projects,
    required List<ProjectTask> tasks,
    required List<Member> members,
    MonthlyAnalyticsSnapshot? monthlySnapshot,
    int minPages = 8,
  }) {
    final data = _HtmlReportData.from(
      report: report,
      projects: projects,
      tasks: tasks,
      members: members,
      monthlySnapshot: monthlySnapshot,
    );

    final companyName = data.companyName;

    final pageBodies = <String>[
      _pageOne(report, data),
      _pageTwo(data),
      _pageThree(data),
      _pageFour(data),
      _pageFive(data),
      _pageSix(data),
      _pageSeven(report, data),
      _pageEight(report, data),
    ];

    if (data.projects.length > 5) {
      for (final chunk in _chunk(data.projects.skip(5).toList(), 12)) {
        pageBodies.add(_projectContinuation(chunk));
      }
    }
    if (data.tasks.length > 7) {
      for (final chunk in _chunk(data.tasks.skip(7).toList(), 14)) {
        pageBodies.add(_taskContinuation(chunk, data));
      }
    }
    if (data.members.length > 5) {
      for (final chunk in _chunk(data.members.skip(5).toList(), 12)) {
        pageBodies.add(_memberContinuation(chunk, data));
      }
    }

    while (pageBodies.length < math.max(8, minPages)) {
      pageBodies.add(_minimumContinuation(report, pageBodies.length + 1));
    }

    final totalPages = pageBodies.length;
    final pages = <String>[];
    for (var index = 0; index < pageBodies.length; index += 1) {
      pages.add(
        _pageShell(
          pageNumber: index + 1,
          totalPages: totalPages,
          accent: _pageAccent(index),
          companyName: companyName,
          body: pageBodies[index],
        ),
      );
    }

    final title = _escape(
      '${report.reportType}_${report.monthId.isEmpty ? report.period : report.monthId}',
    );

    return '''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>$title</title>
<style>
$_css
</style>
</head>
<body>
<main class="report-document">
${pages.join('\n')}
</main>
</body>
</html>''';
  }

  String _pageOne(ReportModel report, _HtmlReportData data) {
    final visibleProjects = data.projects.take(5).toList(growable: false);
    final companyName = _escape(data.companyName);
    final companyInitial = _escape(data.companyName.isNotEmpty ? data.companyName[0].toUpperCase() : 'C');
    final generatedBy = _escape(data.generatedBy);
    final scope = _escape(data.scopeLabel);

    return '''
<section class="annual-cover">
  <div class="cover-brand">
    <div class="cover-emblem">$companyInitial</div>
    <div>
      <strong>$companyName</strong>
      <span>Enterprise reporting intelligence</span>
    </div>
  </div>

  <div class="cover-copy">
    <div class="cover-kicker">${_escape(data.monthLabel)}</div>
    <h1>Monthly<br><span>Management Report</span></h1>
    <p>${_escape(report.summary.isEmpty ? data.executiveSummary : report.summary)}</p>
    <div class="cover-meta">
      <span>Generated by $generatedBy</span>
      <span>Scope: $scope</span>
    </div>
  </div>

  <div class="cover-visual" aria-hidden="true">
    <div class="cover-image-grid"></div>
    <div class="cover-arc cover-arc-large"></div>
    <div class="cover-arc cover-arc-small"></div>
    <div class="cover-year">${DateTime.now().year}</div>
  </div>
</section>

<div class="cover-summary-band">
  <div>
    <span class="eyebrow">Executive snapshot</span>
    <strong>${data.projectCount} projects · ${data.taskCount} tasks · ${data.memberCount} members</strong>
  </div>
  <div class="cover-score">
    <span>${data.overallCompletion}%</span>
    <small>portfolio health</small>
  </div>
</div>

<div class="metrics metrics-4 editorial-metrics">
  ${_metricCard('P', '${data.projectCount}', 'Projects', 'purple')}
  ${_metricCard('T', '${data.taskCount}', 'Work items', 'blue')}
  ${_metricCard('%', '${data.overallCompletion}%', 'Completion', 'green')}
  ${_metricCard('!', '${data.overdueTasks}', 'Late tasks', 'red')}
</div>

<div class="editorial-columns">
  <div>
    ${_sectionTitle('Executive Summary', 'blue')}
    <p class="body-copy">${_escape(data.executiveSummary)}</p>
    <div class="callout-grid">
      ${_callout('Top Risk', data.topRisk, 'orange')}
      ${_callout('Best Signal', data.bestSignal, 'green')}
      ${_callout('Next Action', data.nextAction, 'blue')}
    </div>
  </div>
  <aside class="editorial-sidebar">
    <span class="eyebrow">Portfolio snapshot</span>
    ${_projectTable(visibleProjects)}
  </aside>
</div>
''';
  }

  String _pageTwo(_HtmlReportData data) {
    final statusCounts = <String, int>{};
    for (final project in data.projects) {
      statusCounts[project.status.label] =
          (statusCounts[project.status.label] ?? 0) + 1;
    }

    return '''
${_titleBlock(
  'Portfolio Delivery Health',
  'Project-level health, schedule confidence, status mix and forecast.',
)}
${_sectionTitle('Status Distribution', 'purple')}
<div class="panel">
  ${_stackedDistribution(statusCounts)}
</div>
${_sectionTitle('Project Health Matrix', 'blue')}
${_projectHealthTable(data.projects.take(7).toList(growable: false))}
${_sectionTitle('Progress & Forecast', 'teal')}
<div class="progress-list">
  ${data.projects.take(6).map((project) => _progressRow(project.name, project.progress, _progressColor(project.progress))).join()}
</div>
${_wideCallout(
  'Portfolio forecast',
  data.portfolioForecast,
  'purple',
)}
''';
  }

