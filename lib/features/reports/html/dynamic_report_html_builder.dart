  final ReportModel report;
  final List<Project> projects;
  final List<ProjectTask> tasks;
  final List<Member> members;
  final String companyName;
  final String generatedBy;
  final String monthLabel;
  final String scopeLabel;
  final int projectCount;
  final int taskCount;
  final int memberCount;
  final int completedTasks;
  final int overdueTasks;
  final int overallCompletion;
  final int onlineMembers;
  final int totalAssignments;
  final int averageUtilization;
  final int reviewedMembers;
  final int averageAppraisalScore;
  final int highRatingMembers;
  final int followUpMembers;
  final String executiveSummary;
  final String topRisk;
  final String bestSignal;
  final String nextAction;
  final String portfolioForecast;
  final String criticalChain;
  final String strongestDelivery;
  final String coachingFocus;
  final Map<String, int> taskStatusCounts;
  final Map<String, int> taskPriorityCounts;
  final List<int> weeklyThroughput;
  final List<int> appraisalTrend;
  final Map<String, int> notificationReadiness;

  int get openTasks => math.max(0, taskCount - completedTasks);
  int get taskCompletionRate => taskCount == 0 ? 0 : (completedTasks * 100 / taskCount).round();

  List<ProjectTask> get timelineTasks {
    final output = tasks.where((task) => task.startDate != null || task.createdAt != null).toList();
    output.sort((a, b) {
      final aStart = a.startDate ?? a.createdAt ?? a.dueDate;
      final bStart = b.startDate ?? b.createdAt ?? b.dueDate;
      return aStart.compareTo(bStart);
    });
    return output;
  }

  int get highRatingPercent =>
      reviewedMembers == 0 ? 0 : (highRatingMembers * 100 / reviewedMembers).round();

  int get followUpPercent =>
      reviewedMembers == 0 ? 0 : (followUpMembers * 100 / reviewedMembers).round();

  int get mediumRatingPercent =>
      (100 - highRatingPercent - followUpPercent).clamp(0, 100).toInt();

  String get primaryRiskOwner => tasks.isEmpty ? 'Team Lead' : assigneeNames(tasks.first.assignedToIds);
  String get primaryRiskDue => tasks.isEmpty ? '-' : _short(tasks.first.dueDate);
  String get secondaryRiskDue => tasks.length < 2 ? '-' : _short(tasks[1].dueDate);
  String get tertiaryRiskDue => tasks.length < 3 ? '-' : _short(tasks[2].dueDate);

  static _HtmlReportData from({
    required ReportModel report,
    required List<Project> projects,
    required List<ProjectTask> tasks,
    required List<Member> members,
    required MonthlyAnalyticsSnapshot? monthlySnapshot,
  }) {
    final companyName = report.metrics['companyName']?.toString().trim().isNotEmpty == true
        ? report.metrics['companyName'].toString().trim()
        : 'Company Workspace';

    final namesByUid = <String, String>{
      for (final member in members) member.uid: member.displayName,
    };

    final rawGeneratedBy = report.metrics['generatedByName']?.toString().trim() ??
        report.generatedBy?.trim() ??
        '';
    final generatedBy = namesByUid[rawGeneratedBy] ??
        (rawGeneratedBy.isNotEmpty ? rawGeneratedBy : 'Platform Admin');

    final completed = monthlySnapshot?.metricInt('tasksCompleted') ??
        tasks.where((task) => task.isCompleted).length;
    final overdue = monthlySnapshot?.metricInt('tasksOverdue') ??
        tasks.where((task) => task.isOverdue).length;
    final projectCount = monthlySnapshot?.metricInt('projectCount') ?? projects.length;
    final taskCount = monthlySnapshot?.metricInt('taskCount') ?? tasks.length;
    final memberCount = monthlySnapshot?.metricInt('memberCount') ?? members.length;
    final completion = monthlySnapshot?.metricInt('completionRate') ??
        (tasks.isEmpty ? 0 : (completed * 100 / tasks.length).round());
    final online = members.where((member) => member.isOnline).length;

    final statusCounts = <String, int>{};
    final priorityCounts = <String, int>{};
    for (final task in tasks) {
      statusCounts[task.status.label] = (statusCounts[task.status.label] ?? 0) + 1;
      priorityCounts[task.priority.label] = (priorityCounts[task.priority.label] ?? 0) + 1;
    }

    final reviewed = members.where((member) {
      return member.appraisalScore > 0 ||
          member.appraisalNotes.trim().isNotEmpty ||
          (member.appraisalStatus.trim().isNotEmpty &&
              member.appraisalStatus != 'notReviewed');
    }).toList();
    final averageScore = reviewed.isEmpty
        ? 0
        : (reviewed.fold<int>(0, (sum, member) => sum + member.appraisalScore) /
                reviewed.length)
            .round();
    final highRatings =
        reviewed.where((member) => member.appraisalScore >= 80).length;
    final followUps =
        reviewed.where((member) => member.appraisalScore > 0 && member.appraisalScore < 60).length;

    final assignments = tasks.fold<int>(
      0,
      (sum, task) => sum + math.max(1, task.assignedToIds.length),
    );
    final utilizations = members.map((member) {
      final assigned = tasks.where((task) => task.assignedToIds.contains(member.uid)).length;
      final capacity = member.capacityHoursPerWeek <= 0
          ? 40
          : member.capacityHoursPerWeek.toDouble();
      return (assigned * 8 * 100 / capacity).clamp(0, 100).round();
    }).toList();
    final averageUtilization = utilizations.isEmpty
        ? 0
        : (utilizations.reduce((a, b) => a + b) / utilizations.length).round();

    final sortedRiskTasks = tasks
        .where((task) => task.isOverdue || task.priority.index >= 2)
        .toList()
      ..sort((a, b) {
        if (a.isOverdue != b.isOverdue) return a.isOverdue ? -1 : 1;
        return b.priority.index.compareTo(a.priority.index);
      });
    final topRisk = sortedRiskTasks.isEmpty
        ? 'No overdue or critical work is currently visible.'
        : '${sortedRiskTasks.first.title} requires management attention.';

    final bestProject = projects.isEmpty
        ? null
        : (projects.toList()..sort((a, b) => b.progress.compareTo(a.progress))).first;
    final bestSignal = bestProject == null
        ? 'No project delivery signal is available yet.'
        : '${bestProject.name} reached ${bestProject.progress}% completion.';

    final nextAction = overdue > 0
        ? 'Recover overdue work and confirm ownership before the next reporting cut-off.'
        : 'Complete dependency QA and approve the HTML/CSS print export.';

    final executiveSummary = overdue == 0
        ? 'Delivery health is stable for $companyName. The reporting scope contains $projectCount project(s), no overdue work, and $completion% overall completion.'
        : 'Delivery requires attention for $companyName. The reporting scope contains $projectCount project(s), $overdue overdue task(s), and $completion% overall completion.';

    final portfolioForecast = overdue == 0
        ? 'Most visible workstreams are on track. Continue dependency QA and protect release capacity before the end of the reporting period.'
        : '$overdue overdue task(s) may affect delivery confidence. Rebalance capacity and close dependency blockers before the next milestone.';

    final criticalNames = sortedRiskTasks.take(3).map((task) => task.title).toList();
    final criticalChain = criticalNames.isEmpty
        ? 'No critical dependency chain is visible. Add predecessor task IDs to generate a production critical path.'
        : '${criticalNames.join(' -> ')}. Delays in this chain can move the release milestone.';

    final strongest = members.isEmpty
        ? 'No scored employee performance is available.'
        : (members.toList()
              ..sort((a, b) => b.appraisalScore.compareTo(a.appraisalScore)))
            .first;
    final strongestDelivery = strongest is Member && strongest.appraisalScore > 0
        ? '${strongest.displayName} shows the strongest visible appraisal score at ${strongest.appraisalScore}%.'
        : 'Delivery leadership should be confirmed after the appraisal cycle is completed.';

    final coachingMember = members.isEmpty
        ? null
        : (members.toList()
              ..sort((a, b) => a.appraisalScore.compareTo(b.appraisalScore)))
            .first;
    final coachingFocus = coachingMember == null || coachingMember.appraisalScore == 0
        ? 'Protect QA and review capacity during release weeks to avoid approval bottlenecks.'
        : '${coachingMember.displayName} should receive coaching support based on the current appraisal evidence.';

    final weekly = _weeklyThroughput(tasks);
    final appraisalTrend = _appraisalTrend(averageScore);

    return _HtmlReportData(
      report: report,
      projects: List<Project>.unmodifiable(projects),
      tasks: List<ProjectTask>.unmodifiable(tasks),
      members: List<Member>.unmodifiable(members),
      companyName: companyName,
      generatedBy: generatedBy,
      monthLabel: _monthLabel(report.monthId.isEmpty ? report.period : report.monthId),
      scopeLabel: report.projectScope == 'project'
          ? (report.metrics['projectName']?.toString().trim().isNotEmpty == true
              ? report.metrics['projectName'].toString()
              : 'Selected Project')
          : 'All Projects',
      projectCount: projectCount,
      taskCount: taskCount,
      memberCount: memberCount,
      completedTasks: completed,
      overdueTasks: overdue,
      overallCompletion: completion.clamp(0, 100).toInt(),
      onlineMembers: online,
      totalAssignments: assignments,
      averageUtilization: averageUtilization,
      reviewedMembers: reviewed.length,
      averageAppraisalScore: averageScore.clamp(0, 100).toInt(),
      highRatingMembers: highRatings,
      followUpMembers: followUps,
      executiveSummary: executiveSummary,
      topRisk: topRisk,
      bestSignal: bestSignal,
      nextAction: nextAction,
      portfolioForecast: portfolioForecast,
      criticalChain: criticalChain,
      strongestDelivery: strongestDelivery,
      coachingFocus: coachingFocus,
      taskStatusCounts: statusCounts,
      taskPriorityCounts: priorityCounts,
      weeklyThroughput: weekly,
      appraisalTrend: appraisalTrend,
      notificationReadiness: <String, int>{
        'foreground': _metricInt(report.metrics, 'fcmForegroundReadiness'),
        'background': _metricInt(report.metrics, 'fcmBackgroundReadiness'),
        'terminated': _metricInt(report.metrics, 'fcmTerminatedReadiness'),
        'acceptAction': _metricInt(report.metrics, 'fcmAcceptActionReadiness'),
      },
    );
  }

  String projectName(String projectId) {
    for (final project in projects) {
      if (project.projectId == projectId) return project.name;
    }
    return projectId.trim().isEmpty ? 'No project' : projectId;
  }

  String assigneeNames(List<String> memberIds) {
    if (memberIds.isEmpty) return 'Unassigned';
    final names = <String>[];
    for (final memberId in memberIds) {
      Member? match;
      for (final member in members) {
        if (member.uid == memberId) {
          match = member;
          break;
        }
      }
      names.add(match?.displayName ?? memberId);
    }
    return names.join(', ');
  }

  int assignedTaskCount(String memberId) =>
      tasks.where((task) => task.assignedToIds.contains(memberId)).length;

  int completedTaskCount(String memberId) => tasks
      .where((task) => task.isCompleted && task.assignedToIds.contains(memberId))
      .length;

  int memberUtilization(Member member) {
    final assigned = assignedTaskCount(member.uid);
    final capacity = member.capacityHoursPerWeek <= 0
        ? 40
        : member.capacityHoursPerWeek.toDouble();
    return (assigned * 8 * 100 / capacity).clamp(0, 100).round();
  }

  int taskProgress(ProjectTask task) {
    if (task.progressPercent != null) {
      return task.progressPercent!.clamp(0, 100).toInt();
    }
    if (task.isCompleted) return 100;
    final token = task.status.value.toLowerCase();
    if (token.contains('testing')) return 85;
    if (token.contains('review')) return 72;
    if (token.contains('progress')) return 55;
    if (token.contains('todo')) return 20;
    return 8;
  }

  String ratingLabel(int score) {
    if (score >= 80) return 'High';
    if (score >= 60) return 'Medium';
    if (score > 0) return 'Follow-up';
    return 'Not reviewed';
  }

  static int _metricInt(Map<String, dynamic> map, String key) {
    final value = map[key];
    if (value is int) return value.clamp(0, 100).toInt();
    if (value is num) return value.round().clamp(0, 100).toInt();
    return int.tryParse(value?.toString() ?? '')?.clamp(0, 100).toInt() ?? 0;
  }

  static List<int> _weeklyThroughput(List<ProjectTask> tasks) {
    final output = List<int>.filled(7, 0);
    for (final task in tasks.where((task) => task.completedAt != null)) {
      final completedAt = task.completedAt!;
      output[(completedAt.day - 1).clamp(0, 27) ~/ 4] += 1;
    }
    if (output.every((value) => value == 0)) {
      var running = 0;
      for (var index = 0; index < output.length; index += 1) {
        running += tasks.length ~/ math.max(1, output.length);
        output[index] = running;
      }
    }
    return output;
  }

  static List<int> _appraisalTrend(int current) {
    if (current <= 0) return const <int>[0, 0, 0, 0, 0, 0];
    return <int>[
      (current - 18).clamp(0, 100).toInt(),
      (current - 13).clamp(0, 100).toInt(),
      (current - 10).clamp(0, 100).toInt(),
      (current - 6).clamp(0, 100).toInt(),
      (current - 2).clamp(0, 100).toInt(),
      current,
    ];
  }

  static String _monthLabel(String value) {
    const months = <String>[
      'January', 'February', 'March', 'April', 'May', 'June',
      'July', 'August', 'September', 'October', 'November', 'December',
    ];
    final normalized = value.trim();
    final match = RegExp(r'^(\d{4})[-/](\d{1,2})').firstMatch(normalized);
    if (match != null) {
      final year = int.tryParse(match.group(1) ?? '');
      final month = int.tryParse(match.group(2) ?? '');
      if (year != null && month != null && month >= 1 && month <= 12) {
        return '${months[month - 1]} $year';
      }
    }
    return normalized.isEmpty ? 'Reporting Period' : normalized;
  }

  static String _short(DateTime value) {
    const months = <String>[
      'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
      'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
    ];
    return '${value.day.toString().padLeft(2, '0')} ${months[value.month - 1]}';
  }
