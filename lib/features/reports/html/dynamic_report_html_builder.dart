  static String _categoryColor(String value) {
    final token = value.toLowerCase();
    if (token.contains('complete') || token.contains('done') || token.contains('active')) {
      return 'green';
    }
    if (token.contains('critical') || token.contains('overdue') || token.contains('blocked')) {
      return 'red';
    }
    if (token.contains('high') || token.contains('review')) return 'orange';
    if (token.contains('progress') || token.contains('medium')) return 'blue';
    if (token.contains('low') || token.contains('todo')) return 'teal';
    return 'purple';
  }

  static String _progressColor(int value) {
    if (value >= 85) return 'green';
    if (value >= 60) return 'blue';
    if (value >= 35) return 'orange';
    return 'red';
  }

  static String _taskColor(ProjectTask task) {
    if (task.isOverdue) return 'red';
    if (task.isCompleted) return 'green';
    final status = task.status.value.toLowerCase();
    if (status.contains('review')) return 'purple';
    if (task.priority.index >= 2) return 'orange';
    return 'blue';
  }

