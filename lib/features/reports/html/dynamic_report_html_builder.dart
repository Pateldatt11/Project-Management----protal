  String _memberPerformanceTable(List<Member> members, _HtmlReportData data) {
    final rows = members.isEmpty
        ? '<tr><td colspan="6" class="empty-cell">No employee data in this scope.</td></tr>'
        : members.map((member) {
            final assigned = data.assignedTaskCount(member.uid);
            final completed = data.completedTaskCount(member.uid);
            final score = member.appraisalScore;
            return '''
<tr>
  <td>${_escape(member.displayName)}</td>
  <td>${_escape(member.role.label)}</td>
  <td>$assigned</td>
  <td>$completed</td>
  <td>$score%</td>
  <td>${_escape(data.ratingLabel(score))}</td>
</tr>''';
          }).join();

    return '''
<table class="report-table">
  <thead>
    <tr><th>Member</th><th>Role</th><th>Tasks</th><th>Done</th><th>Score</th><th>Rating</th></tr>
  </thead>
  <tbody>$rows</tbody>
</table>''';
  }

  String _auditTable(ReportModel report, _HtmlReportData data) {
    final rows = <List<String>>[
      <String>['Registered company', data.companyName],
      <String>['Report type', report.reportType],
      <String>['Project scope', data.scopeLabel],
      const <String>['Minimum pages', '8'],
      const <String>['Dynamic overflow', 'Enabled - additional pages generated from real data'],
      const <String>['Data sources', 'Projects, tasks, members, timeline, appraisal, workload, notifications'],
      <String>['Generated by', data.generatedBy],
      const <String>['Permission', 'Admin / PM / TL can generate and export'],
      const <String>['Export formats', 'HTML, browser print, Save as PDF, CSV'],
    ];
    return '''
<table class="report-table audit-table">
  <thead><tr><th>Field</th><th>Value</th></tr></thead>
  <tbody>
  ${rows.map((row) => '<tr><td>${_escape(row[0])}</td><td>${_escape(row[1])}</td></tr>').join()}
  </tbody>
</table>''';
  }

  String _stackedDistribution(Map<String, int> values) {
    final entries = values.entries.where((entry) => entry.value > 0).toList();
    final total = entries.fold<int>(0, (sum, entry) => sum + entry.value);
    if (total == 0) {
      return '<div class="empty-chart">No distribution data available.</div>';
    }

    final colors = <String>['green', 'blue', 'purple', 'orange', 'teal', 'red'];
