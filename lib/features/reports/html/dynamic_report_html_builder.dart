  String _lineChart(List<int> values, List<String> labels, String color) {
    final safeValues = values.isEmpty ? const <int>[0] : values;
    final count = math.max(2, safeValues.length);
    const width = 720.0;
    const height = 150.0;
    const left = 20.0;
    const right = 20.0;
    const top = 18.0;
    const bottom = 28.0;
    final chartWidth = width - left - right;
    final chartHeight = height - top - bottom;
    final maxValue = math.max(1, safeValues.fold<int>(0, (a, b) => math.max(a, b).toInt())).toInt();

    final points = <String>[];
    final circles = <String>[];
    final labelNodes = <String>[];
    for (var index = 0; index < safeValues.length; index += 1) {
      final x = left + chartWidth * index / (count - 1);
      final y = top + chartHeight * (1 - safeValues[index] / maxValue);
      points.add('${x.toStringAsFixed(1)},${y.toStringAsFixed(1)}');
      circles.add(
        '<circle cx="${x.toStringAsFixed(1)}" cy="${y.toStringAsFixed(1)}" r="5" fill="#fff" stroke="$color" stroke-width="3"/>',
      );
      final label = index < labels.length ? labels[index] : 'P${index + 1}';
      labelNodes.add(
        '<text x="${x.toStringAsFixed(1)}" y="${height - 7}" text-anchor="middle" class="svg-label">${_escape(label)}</text>',
      );
    }

    final grid = <String>[];
    for (var index = 0; index < 4; index += 1) {
      final y = top + chartHeight * index / 3;
      grid.add(
        '<line x1="$left" y1="${y.toStringAsFixed(1)}" x2="${width - right}" y2="${y.toStringAsFixed(1)}" class="svg-grid"/>',
      );
    }

    return '''
<svg class="line-chart" viewBox="0 0 $width $height" role="img" aria-label="Trend line chart">
  ${grid.join()}
  <polyline points="${points.join(' ')}" fill="none" stroke="$color" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"/>
  ${circles.join()}
  ${labelNodes.join()}
</svg>''';
  }

  String _gantt(List<ProjectTask> tasks, _HtmlReportData data) {
    if (tasks.isEmpty) {
      return '<div class="empty-chart">Add task start dates to generate the delivery timeline.</div>';
    }

    final starts = tasks.map((task) => task.startDate ?? task.createdAt ?? task.dueDate).toList();
    final ends = tasks.map((task) => task.dueDate).toList();
    var minDate = starts.reduce((a, b) => a.isBefore(b) ? a : b);
    var maxDate = ends.reduce((a, b) => a.isAfter(b) ? a : b);
    if (!maxDate.isAfter(minDate)) {
      maxDate = minDate.add(const Duration(days: 1));
    }
    final totalDays = math.max(1, maxDate.difference(minDate).inDays + 1);
    final todayOffset = DateTime.now().difference(minDate).inDays;
    final todayPercent = (todayOffset * 100 / totalDays).clamp(0, 100).toDouble();

    final rows = tasks.asMap().entries.map((entry) {
      final task = entry.value;
      final start = task.startDate ?? task.createdAt ?? task.dueDate;
      final startOffset = start.difference(minDate).inDays;
      final endOffset = task.dueDate.difference(minDate).inDays + 1;
      final left = (startOffset * 100 / totalDays).clamp(0, 100).toDouble();
      final width = ((endOffset - startOffset) * 100 / totalDays).clamp(4, 100 - left).toDouble();
      final color = _taskColor(task);
      final milestone = task.isMilestone
          ? '<span class="milestone $color" style="left:calc(${(left + width).clamp(0, 100).toStringAsFixed(2)}% - 7px)"></span>'
          : '';
      return '''
<div class="gantt-row">
  <div class="gantt-label">${_escape(task.title)}</div>
  <div class="gantt-track">
    <span class="gantt-bar $color" style="left:${left.toStringAsFixed(2)}%;width:${width.toStringAsFixed(2)}%"></span>
    $milestone
  </div>
</div>''';
    }).join();

    return '''
<div class="gantt-head">
  <div>Work item</div>
  <div>${_escape(data.monthLabel)}</div>
</div>
<div class="gantt-body">
  <div class="today-line" style="left:calc(31% + ${todayPercent.toStringAsFixed(2)}% * .69)">
    <span>TODAY</span>
  </div>
  $rows
</div>''';
  }

