  String _pageShell({
    required int pageNumber,
    required int totalPages,
    required String accent,
    required String companyName,
    required String body,
  }) {
    final companyInitial = _escape(companyName.isNotEmpty ? companyName[0].toUpperCase() : 'C');
    return '''
<section class="report-page page-$pageNumber" style="--accent:$accent">
  <div class="editorial-sweep" aria-hidden="true"></div>
  <div class="editorial-orb editorial-orb-a" aria-hidden="true"></div>
  <div class="editorial-orb editorial-orb-b" aria-hidden="true"></div>
  <header class="page-header">
    <div class="brand">
      <div class="brand-mark">$companyInitial</div>
      <div class="brand-name">${_escape(companyName)}</div>
    </div>
    <div class="page-number">Page $pageNumber</div>
  </header>
  <div class="page-content">
    $body
  </div>
  <footer class="page-footer">
    <div class="footer-left">
      <span class="footer-accent"></span>
      <span>Generated for ${_escape(companyName)} - confidential internal report</span>
    </div>
    <div>HTML / PDF export&nbsp;&nbsp;|&nbsp;&nbsp;Page $pageNumber of $totalPages</div>
  </footer>
</section>''';
  }

