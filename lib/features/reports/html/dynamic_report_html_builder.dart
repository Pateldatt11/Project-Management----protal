  <td>${_escape(project.name)}</td>
  <td>${_escape(project.status.label)}</td>
  <td>${project.progress}%</td>
  <td>${_escape(_projectOwner(project))}</td>
  <td>${_dateShort(project.startDate)} - ${_dateShort(project.dueDate)}</td>
</tr>''';
          }).join();

    return '''
<table class="report-table">
  <thead>
    <tr><th>Project</th><th>Status</th><th>Done</th><th>Owner</th><th>Schedule</th></tr>
